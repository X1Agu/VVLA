"""Installed OFT environment plus real vision/small-text random-checkpoint check."""
import argparse
import json
import os
from pathlib import Path
import subprocess
import tempfile
from check_release import run

root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--oft-python',type=Path,required=True)
parser.add_argument('--wheels',type=Path,required=True)
parser.add_argument('--source',type=Path,required=True)
parser.add_argument('--transformers-source',type=Path,required=True)
parser.add_argument('--checkpoint',type=Path,help='Reuse an existing synthetic checkpoint generated by this tool')
parser.add_argument('--native',type=Path,required=True,help='Pinned vLLM native operator asset')
args=parser.parse_args()
work=Path(tempfile.mkdtemp(prefix='oft-installed-',dir=root/'artifacts'))
env=dict(os.environ);env.pop('PYTHONPATH',None)
env['PATH']=str(args.oft_python.parent)+os.pathsep+env['PATH']
run([args.oft_python,'-m','venv',work/'installed'],cwd=work,env=env,log=work/'venv.log')
site=next((work/'installed/lib').glob('python*/site-packages'))
dependencies=subprocess.check_output([args.oft_python,'-c',"import sysconfig; print(sysconfig.get_paths()['purelib'])"],text=True).strip()
(site/'dependencies.pth').write_text(dependencies+'\n')
python=work/'installed/bin/python'
wheels=[p for p in args.wheels.glob('*.whl') if p.name.startswith(('vvla-','vvla_runtime-','vvla_oft-'))]
if len(wheels)!=3:raise RuntimeError('Expected exactly SDK/runtime/OFT wheels')
run([python,'-m','pip','install','--no-index','--no-deps',*wheels],cwd=work,env=env,log=work/'install.log')
run([python,'-m','pip','install','--ignore-installed','--no-deps','setuptools==80.10.2','ninja==1.13.2'],cwd=work,env=env,log=work/'setuptools.log')
checkpoint=args.checkpoint.resolve(strict=True) if args.checkpoint else work/'random-debug-checkpoint'
if args.checkpoint is None:
    run([python,'-I',root/'tools/make_oft_debug_checkpoint.py','--source',args.source,'--output',checkpoint],
        cwd=work,env=env,log=work/'checkpoint.log')
probe=work/'gpu_probe.py'
probe.write_text('''import json,pathlib,numpy as np,torch,vvla,vvla_oft
from vvla import load
expected=pathlib.Path(__file__).parent/'installed'
assert pathlib.Path(vvla.__file__).is_relative_to(expected)
assert pathlib.Path(vvla_oft.__file__).is_relative_to(expected)
settings=json.loads(pathlib.Path(__file__).with_name('settings.json').read_text())
observation={'full_image':np.zeros((256,256,3),np.uint8),'wrist_image':np.full((256,256,3),127,np.uint8),
             'state':np.zeros(8,np.float32),'prompt':'pick the red block','norm_key':'debug'}
results={}
for recipe in ['official-bf16','bf16','mlp-fp8']:
    with load('oft',checkpoint=settings['checkpoint'],assets=settings['assets'],recipe=recipe,
              options={'norm_key':'debug','batch_size':1},timeout_s=600) as engine:
        first=engine.infer_batch([observation],[17])[0]
        before=first.copy()
        again=engine.infer_batch([observation],[29])[0]
        np.testing.assert_array_equal(first,again)
        changed=dict(observation,full_image=np.full((256,256,3),255,np.uint8))
        different=engine.infer_batch([changed],[17])[0]
        assert not np.array_equal(first,different), 'Changed camera was ignored'
        np.testing.assert_array_equal(first,before)
        assert first.shape==(8,7) and np.isfinite(first).all()
        results[recipe]={'actions':first.tolist(),'metadata':engine.metadata(),'image_sensitive':not np.array_equal(first,different)}
        engine.reset('new');engine.close()
a=np.array(results['official-bf16']['actions']);b=np.array(results['bf16']['actions'])
np.testing.assert_allclose(a,b,rtol=.025,atol=.025)
c=np.array(results['mlp-fp8']['actions'])
assert np.linalg.norm(b)>1e-6, 'Degenerate synthetic reference cannot validate precision'
fp8_relative_rms=float(np.linalg.norm(c-b)/np.linalg.norm(b))
assert fp8_relative_rms<=.15, ('Gross FP8 mechanism drift',fp8_relative_rms)
pathlib.Path(__file__).with_name('result.json').write_text(json.dumps(dict(status='passed',synthetic_weights=True,
    quality_qualified=False,official_native_tolerance={'rtol':.025,'atol':.025},
    fp8_vs_native_relative_rms=fp8_relative_rms,fp8_gross_mechanism_bound=.15,results=results),indent=2))
''')
(work/'settings.json').write_text(json.dumps(dict(checkpoint=str(checkpoint),assets={
    'source':str(args.source.resolve()),'transformers_source':str(args.transformers_source.resolve()),
    'native':str(args.native.resolve())})))
run([python,'-I',probe],cwd=work,env=env,log=work/'gpu.log')
print(json.dumps(dict(status='passed',artifacts=str(work))))
